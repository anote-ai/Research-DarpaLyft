"""Run the implemented continual-learning metric suite over synthetic task
sequences and write the *actually measured* outputs to results/cl_metrics.json
and results/cl_metrics.md.

IMPORTANT SCOPE NOTE: this script exercises the toy/synthetic continual-learning
metrics already implemented in src/darpalyft/{core,data,evaluate}.py (TaskRecord,
TaskSequence, forward_transfer, backward_transfer, continual_learning_score,
plasticity_score, stability_score, domain_drift_penalty). It does NOT implement
or run the methods described in DESIGN_DOC.md (EWC, iCaRL, GEM, MAML, Meta-CL,
LYFT-Bench, Jetson edge deployment) -- those remain unimplemented. The numbers
produced here are real (computed by running this code), but they describe
synthetic, hand-authored accuracy curves, not a trained model. They should NOT
be read as evidence for the design doc's FTR >= 0.50 / forgetting < 0.10 claims.
"""
from __future__ import annotations

import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from darpalyft.data import (
    make_catastrophic_forgetting_sequence,
    make_iid_sequence,
    make_task_sequence,
)
from darpalyft.evaluate import (
    backward_transfer,
    continual_learning_score,
    domain_drift_penalty,
    forward_transfer,
    plasticity_score,
    stability_score,
)


def summarize(name: str, seq) -> dict:
    return {
        "sequence": name,
        "n_tasks": len(seq.records),
        "domain_drift_count": seq.domain_drift_count(),
        "backward_transfer": round(backward_transfer(seq), 4),
        "forward_transfer": round(forward_transfer(seq), 4),
        "continual_learning_score": round(continual_learning_score(seq), 4),
        "plasticity_score": round(plasticity_score(seq), 4),
        "stability_score": round(stability_score(seq), 4),
        "domain_drift_penalty": round(domain_drift_penalty(seq), 4),
    }


def main() -> None:
    seeds = [0, 1, 2, 3, 4]
    rows = []

    for seed in seeds:
        rows.append(summarize(f"drift_seed{seed}", make_task_sequence(n_tasks=6, seed=seed, domain_drift=True)))
        rows.append(summarize(f"iid_seed{seed}", make_iid_sequence(n_tasks=6, seed=seed)))
        rows.append(summarize(f"catastrophic_seed{seed}", make_catastrophic_forgetting_sequence(n_tasks=5, seed=seed)))

    out_dir = os.path.join(os.path.dirname(__file__), "..", "results")
    os.makedirs(out_dir, exist_ok=True)

    json_path = os.path.join(out_dir, "cl_metrics.json")
    with open(json_path, "w") as f:
        json.dump(rows, f, indent=2)

    md_path = os.path.join(out_dir, "cl_metrics.md")
    with open(md_path, "w") as f:
        f.write("# Continual Learning Metric Suite -- Measured Output\n\n")
        f.write(
            "Generated by `scripts/run_cl_experiments.py` against the synthetic "
            "task-sequence generators in `src/darpalyft/data.py` and the metric "
            "implementations in `src/darpalyft/evaluate.py`. These are real "
            "computed values from running the code in this repo, on synthetic "
            "hand-authored accuracy curves -- **not** results from training "
            "EWC / iCaRL / GEM / MAML / Meta-CL on LYFT-Bench as described in "
            "DESIGN_DOC.md. Treat as a smoke-test / metric-validation artifact, "
            "not as evidence for the design doc's experimental claims.\n\n"
        )
        f.write("| Sequence | n_tasks | Drift count | BWT | FWT | CL Score | Plasticity | Stability | Drift penalty |\n")
        f.write("|---|---|---|---|---|---|---|---|---|\n")
        for r in rows:
            f.write(
                f"| {r['sequence']} | {r['n_tasks']} | {r['domain_drift_count']} | "
                f"{r['backward_transfer']} | {r['forward_transfer']} | "
                f"{r['continual_learning_score']} | {r['plasticity_score']} | "
                f"{r['stability_score']} | {r['domain_drift_penalty']} |\n"
            )

    print(f"Wrote {json_path} and {md_path}")
    for r in rows:
        print(r)


if __name__ == "__main__":
    main()
